#include "main.h"
#include "lcd_i2c.h"
#include "keypad.h"

I2C_HandleTypeDef hi2c1;

void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_I2C1_Init(void);
int main(void)
{
    HAL_Init();
    SystemClock_Config();
    MX_GPIO_Init();
    MX_I2C1_Init();

    // Initialize LCD and Keypad
    LCD_Init(&hi2c1);
    Keypad_Init();

    // Display initial message
    LCD_Clear(&hi2c1);
    LCD_SetCursor(&hi2c1, 0, 0);
    LCD_SendString(&hi2c1, "Press any key: ");

    char last_key = '\0';
    char current_key = '\0';

    while (1)
    {
        current_key = Keypad_GetKey();

        if (current_key != '\0' && current_key != last_key)
        {
            // Clear second line and display the key
            LCD_SetCursor(&hi2c1, 1, 0);
            LCD_SendString(&hi2c1, "                ");
            LCD_SetCursor(&hi2c1, 1, 0);

            // Display the pressed key
            char display_str[2] = {current_key, '\0'};
            LCD_SendString(&hi2c1, display_str);

            last_key = current_key;
        }
        else if (current_key == '\0')
        {
            last_key = '\0';
        }

        // Small delay to prevent flooding
        HAL_Delay(100);
    }
}

