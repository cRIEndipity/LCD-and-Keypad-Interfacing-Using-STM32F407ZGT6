#include "main.h"
#include "lcd_i2c.h"
#include <stdio.h>  // Add this for sprintf
#include <string.h> // Add this for string functions

I2C_HandleTypeDef hi2c1;

void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_I2C1_Init(void);

int main(void) {
    HAL_Init();
    SystemClock_Config();
    MX_GPIO_Init();
    MX_I2C1_Init();

    // Initialize LCD
    LCD_Init(&hi2c1);

    // Variable for seconds counter
    int seconds = 0;
    char buffer[20]; // Buffer for converting int to string

    // Display static text on first line
    LCD_SetCursor(&hi2c1, 0, 1);
    LCD_SendString(&hi2c1, "Time running");

    while (1) {
        // Convert seconds to string
        snprintf(buffer, sizeof(buffer), "Seconds: %d", seconds);

        // Calculate center position for timer text (length = 10 + digits)
        uint8_t text_length = strlen(buffer);
        uint8_t start_pos = (16 - text_length) / 2;

        // Display timer on second line
        LCD_SetCursor(&hi2c1, 1, 0);
        LCD_SendString(&hi2c1, "                ");
        LCD_SetCursor(&hi2c1, 1, start_pos);
        LCD_SendString(&hi2c1, buffer);

        // Wait for 1 second
        HAL_Delay(1000);

        // Increase seconds counter
        seconds++;

        // Reset after reaching a certain value (optional)
        if (seconds > 9999) {
            seconds = 0;
        }
    }
}

